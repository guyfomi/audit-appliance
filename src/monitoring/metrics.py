"""
Métriques Prometheus — Oracle Data Audit & Forensics Appliance.
Endpoint GET /metrics — scrappable par Prometheus ou Grafana Agent.
"""
from __future__ import annotations

from fastapi import APIRouter
from fastapi.responses import Response
from prometheus_client import (
    Counter, Gauge, Histogram,
    CollectorRegistry, generate_latest, CONTENT_TYPE_LATEST,
    multiprocess,
)

metrics_router = APIRouter(tags=["monitoring"])

# ── Compteurs ─────────────────────────────────────────────────────────────────

events_processed = Counter(
    "audit_events_processed_total",
    "Total events processed by the audit engine",
    ["operation", "risk_level"],
)
events_duplicated = Counter(
    "audit_events_duplicated_total",
    "Events discarded as duplicates",
)
events_failed = Counter(
    "audit_events_failed_total",
    "Events that failed processing",
)
alerts_generated = Counter(
    "audit_alerts_generated_total",
    "Alerts generated by the risk engine",
    ["severity"],
)

# ── Jauges ────────────────────────────────────────────────────────────────────

cdc_lag_seconds = Gauge(
    "audit_cdc_lag_seconds",
    "Current CDC lag in seconds",
    ["database"],
)
events_per_second = Gauge(
    "audit_events_per_second",
    "Current event throughput (events/sec)",
)
open_alerts_gauge = Gauge(
    "audit_open_alerts_total",
    "Number of open alerts by severity",
    ["severity"],
)
disk_free_bytes = Gauge(
    "audit_disk_free_bytes",
    "Free disk space on the appliance",
)
pg_size_bytes = Gauge(
    "audit_postgresql_size_bytes",
    "PostgreSQL database size in bytes",
)
integrity_ok_gauge = Gauge(
    "audit_integrity_chain_ok",
    "1 if the integrity chain is valid, 0 otherwise",
)

# ── Histogrammes ──────────────────────────────────────────────────────────────

pipeline_duration = Histogram(
    "audit_pipeline_duration_seconds",
    "Time to process one event through the full pipeline",
    buckets=[0.001, 0.005, 0.01, 0.05, 0.1, 0.5, 1.0, 5.0],
)
api_request_duration = Histogram(
    "audit_api_request_duration_seconds",
    "API request latency",
    ["method", "path", "status"],
    buckets=[0.01, 0.05, 0.1, 0.25, 0.5, 1.0, 5.0],
)
db_write_latency = Histogram(
    "audit_db_write_latency_seconds",
    "PostgreSQL write latency for audit_event",
    buckets=[0.001, 0.005, 0.01, 0.05, 0.1, 0.5],
)


# ── Endpoint Prometheus ───────────────────────────────────────────────────────

@metrics_router.get("/metrics")
async def prometheus_metrics():
    """
    Endpoint Prometheus standard — scrappable sans authentification
    (protégé par firewall au niveau réseau en production).
    """
    return Response(generate_latest(), media_type=CONTENT_TYPE_LATEST)
